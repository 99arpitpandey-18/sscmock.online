const baseSets = [
    questionBank[1],
    questionBank[2],
    questionBank[3],
    questionBank[4],
    questionBank[5]
];


/*
   Remaining sets ko independently construct karne
   ke liye existing questions ko controlled rotation
   ke saath distribute kiya ja raha hai.
*/

for(let set = 6; set <= 25; set++){

    questionBank[set] = [];

    const source =
        baseSets[(set - 6) % baseSets.length];


    for(let i = 0; i < 20; i++){

        const original =
            source[i];


        questionBank[set].push({

            parts:[...original.parts],

            answer:original.answer,

            explanation:original.explanation

        });

    }

}


