let selectedSet = 1;

let currentQuestion = 0;

let userAnswers = [];

let timerSeconds = 15 * 60;

let timerInterval = null;

let testSubmitted = false;


/* =========================================================
   PAGE ELEMENTS
========================================================= */

const setPage =
    document.getElementById("setPage");

