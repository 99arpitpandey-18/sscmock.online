/* =========================================================
   CREATE 25 SETS
========================================================= */

function createSets(){

    const container =
        document.getElementById("setContainer");

    container.innerHTML = "";


    for(let i = 1; i <= 25; i++){

        const div =
            document.createElement("div");

        div.className = "set-card";


        div.innerHTML = `

            <div class="set-number">
                Set ${i}
            </div>

            <small>
                20 Questions
            </small>

        `;


        div.onclick = function(){

            selectSet(i);

        };


        container.appendChild(div);

    }

}


/* =========================================================
   SELECT SET
========================================================= */

function selectSet(setNumber){

    selectedSet = setNumber;


    document.getElementById(
        "startTitle"
    ).textContent =
        "Error Detection - Set " +
        selectedSet;


    setPage.classList.add("hidden");

    startPage.classList.remove("hidden");

    testPage.classList.add("hidden");

    resultPage.classList.add("hidden");


    window.scrollTo(0,0);

}


/* =========================================================
   SHOW ALL SETS
========================================================= */

function showSets(){

    clearInterval(timerInterval);


    setPage.classList.remove("hidden");

    startPage.classList.add("hidden");

    testPage.classList.add("hidden");

    resultPage.classList.add("hidden");


    window.scrollTo(0,0);

}


/* =========================================================
   START TEST
========================================================= */

function startTest(){

    const questions =
        questionBank[selectedSet];


    if(!questions){

        alert(
            "Question bank load nahi hua."
        );

        return;

    }


    if(questions.length !== 20){

        alert(
            "Is set mein 20 questions available nahi hain."
        );

        return;

    }


    currentQuestion = 0;

    userAnswers =
        new Array(20).fill(null);

    testSubmitted = false;

    timerSeconds = 15 * 60;


    clearInterval(timerInterval);


    document.getElementById(
        "testTitle"
    ).textContent =
        "Error Detection - Set " +
        selectedSet;


    setPage.classList.add("hidden");

    startPage.classList.add("hidden");

    resultPage.classList.add("hidden");

    testPage.classList.remove("hidden");


    loadQuestion();

    startTimer();


    window.scrollTo(0,0);

}


/* =========================================================
   TIMER
========================================================= */

function startTimer(){

    updateTimer();


    timerInterval = setInterval(function(){

        if(testSubmitted){

            clearInterval(timerInterval);

            return;

        }


        timerSeconds--;

        updateTimer();


        if(timerSeconds <= 0){

            clearInterval(timerInterval);

            submitTest(true);

        }

    },1000);

}


/* =========================================================
   UPDATE TIMER
========================================================= */

function updateTimer(){

    const minutes =
        Math.floor(timerSeconds / 60);

    const seconds =
        timerSeconds % 60;


    document.getElementById(
        "timer"
    ).textContent =

        String(minutes).padStart(2,"0")
        +
        ":"
        +
        String(seconds).padStart(2,"0");

}


/* =========================================================
   LOAD QUESTION
========================================================= */

function loadQuestion(){

    const questions =
        questionBank[selectedSet];

    const question =
        questions[currentQuestion];


    document.getElementById(
        "questionNumber"
    ).textContent =
        "Question " +
        (currentQuestion + 1);


    document.getElementById(
        "questionCount"
    ).textContent =
        (currentQuestion + 1) +
        " / " +
        questions.length;


    const percentage =
        ((currentQuestion + 1) /
        questions.length) * 100;


    document.getElementById(
        "progress"
    ).style.width =
        percentage + "%";


    /* ==============================================
       ACTUAL SENTENCE
    ============================================== */

    let html = `

        <div class="error-question">

            <h3>
                Q${currentQuestion + 1}.
            </h3>

            <div class="sentence-line">

    `;


    question.parts.forEach(
        function(part,index){

            html += `

                <span class="sentence-part">

                    ${part}

                    ${
                        index <
                        question.parts.length - 1
                        ? " / "
                        : "."
                    }

                </span>

            `;

        }
    );


    html += `

            </div>

        </div>


        <div class="ask-error">

            Which part of the sentence contains an error?

        </div>

        <div class="options">

    `;


    /* ==============================================
       A B C D OPTIONS
    ============================================== */

    question.parts.forEach(
        function(part,index){

            const selected =
                userAnswers[currentQuestion]
                === index;


            html += `

                <label
                    class="option ${
                        selected
                        ? "selected"
                        : ""
                    }"
                >

                    <input
                        type="radio"
                        name="answer"
                        ${
                            selected
                            ? "checked"
                            : ""
                        }
                        onchange="
                            selectAnswer(${index})
                        "
                    >

                    <span class="option-letter">

                        ${String.fromCharCode(
                            65 + index
                        )}

                    </span>

                    <span>
                        ${part}
                    </span>

                </label>

            `;

        }
    );


    html += `</div>`;


    document.getElementById(
        "questionBox"
    ).innerHTML =
        html;


    /* ==============================================
       NAVIGATION
    ============================================== */

    document.getElementById(
        "previousBtn"
    ).disabled =
        currentQuestion === 0;


    if(
        currentQuestion ===
        questions.length - 1
    ){

        document.getElementById(
            "nextBtn"
        ).classList.add("hidden");


        document.getElementById(
            "submitBtn"
        ).classList.remove("hidden");

    }

    else{

        document.getElementById(
            "nextBtn"
        ).classList.remove("hidden");


        document.getElementById(
            "submitBtn"
        ).classList.add("hidden");

    }


    createPalette();

}


